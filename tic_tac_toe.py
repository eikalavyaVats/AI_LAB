import math
import random

def print_board(board):
    for row in range(3):
        print(" | ".join(board[row*3:(row+1)*3]))
        if row < 2:
            print("---------")
    print()

def check_winner(board, player):
    win_states = [
        [0, 1, 2], [3, 4, 5], [6, 7, 8], # rows
        [0, 3, 6], [1, 4, 7], [2, 5, 8], # columns
        [0, 4, 8], [2, 4, 6]             # diagonals
    ]
    return any(all(board[i] == player for i in state) for state in win_states)

def is_board_full(board):
    return " " not in board

def minimax(board, depth, is_maximizing):
    if check_winner(board, 'O'):
        return 1
    if check_winner(board, 'X'):
        return -1
    if is_board_full(board):
        return 0

    if is_maximizing:
        best_score = -math.inf
        for i in range(9):
            if board[i] == " ":
                board[i] = 'O'
                score = minimax(board, depth + 1, False)
                board[i] = " "
                best_score = max(score, best_score)
        return best_score
    else:
        best_score = math.inf
        for i in range(9):
            if board[i] == " ":
                board[i] = 'X'
                score = minimax(board, depth + 1, True)
                board[i] = " "
                best_score = min(score, best_score)
        return best_score

def get_best_move(board):
    best_score = -math.inf
    move = -1
    for i in range(9):
        if board[i] == " ":
            board[i] = 'O'
            score = minimax(board, 0, False)
            board[i] = " "
            if score > best_score:
                best_score = score
                move = i
    return move

def play_game():
    board = [" "] * 9
    print("Welcome to Tic-Tac-Toe! You are 'X' and the AI is 'O'.")
    print("Enter a position from 1 to 9 to make your move.\n")
    print_board([str(i+1) for i in range(9)])

    while True:
        # Player's turn
        while True:
            try:
                move = int(input("Your turn (1-9): ")) - 1
                if 0 <= move <= 8 and board[move] == " ":
                    board[move] = 'X'
                    break
                else:
                    print("Invalid move. Try again.")
            except ValueError:
                print("Please enter a number between 1 and 9.")

        print_board(board)
        if check_winner(board, 'X'):
            print("Congratulations! You won!")
            break
        if is_board_full(board):
            print("It's a tie!")
            break

        # AI's turn
        print("AI's turn...")
        ai_move = get_best_move(board)
        if ai_move != -1:
            board[ai_move] = 'O'

        print_board(board)
        if check_winner(board, 'O'):
            print("AI wins! Better luck next time.")
            break
        if is_board_full(board):
            print("It's a tie!")
            break

# Run the game
play_game()