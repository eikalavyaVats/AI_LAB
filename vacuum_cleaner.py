class VacuumCleaner:
    def __init__(self):
        self.location = "A"
        self.rooms = {
            "A": "Dirty",
            "B": "Dirty"
        }
        self.performance = 0
    def display_environment(self):
        print("\n--- Environment ---")
        print("Room A:", self.rooms["A"])
        print("Room B:", self.rooms["B"])
        print("Vacuum Location:", self.location)
        print("Performance:", self.performance)
    def suck(self):
        if self.rooms[self.location] == "Dirty":
            self.rooms[self.location] = "Clean"
            self.performance += 10
            print("Action: Suck")
        else:
            print("Room is already clean.")
    def move_left(self):
        if self.location == "B":
            self.location = "A"
            self.performance -= 1
            print("Action: Move Left")
        else:
            print("Already at Room A.")
    def move_right(self):
        if self.location == "A":
            self.location = "B"
            self.performance -= 1
            print("Action: Move Right")
        else:
            print("Already at Room B.")
    def run(self):
        print("=== Vacuum Cleaner Agent ===")
        while True:
            self.display_environment()
            if self.rooms["A"] == "Clean" and self.rooms["B"] == "Clean":
                print("\nAll rooms are clean!")
                print("Final Performance:", self.performance)
                break
            print("\nChoose an action:")
            print("1. Suck")
            print("2. Move Left")
            print("3. Move Right")
            print("4. Exit")
            choice = input("Enter your choice: ")
            if choice == "1":
                self.suck()
            elif choice == "2":
                self.move_left()
            elif choice == "3":
                self.move_right()
            elif choice == "4":
                print("Program terminated.")
                break
            else:
                print("Invalid choice. Please try again.")
vacuum = VacuumCleaner()
vacuum.run()